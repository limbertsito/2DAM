    private void jButtonCalcularActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonCalcularActionPerformed
        // TODO add your handling code here:
        Date fecha1 = (Date) jSpinnerRecogerFecha1.getValue();
        Date fecha2 = (Date) jSpinnerRecogerFecha2.getValue();

        //Castewamos las fechas en milisegundos
        long f1 = fecha1.getTime();
        long f2 = fecha2.getTime();
        
        //calculamos la ddiferencia no ignorando que fecha fue antes que la otra , apra segurar que la dfiferencia sea postiva
        
        long diferencia = Math.abs(f1-f2);
        
        //Lo pasamos  a dias milsegundo/segundos/minutos/Horas
        long dias = diferencia/(1000*60*60*24);
        
        jTextFieldMensajeResultado.setText("La diferencia entre ambos dias es de : "+dias);

    }//GEN-LAST:event_jButtonCalcularActionPerformed

