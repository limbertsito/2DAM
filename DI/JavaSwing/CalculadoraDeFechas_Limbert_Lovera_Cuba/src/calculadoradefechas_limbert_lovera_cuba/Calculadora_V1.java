    private void BtnCalcularActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BtnCalcularActionPerformed
        // TODO add your handling code here:
      SimpleDateFormat sdf = new SimpleDateFormat("dd/MM/yyyy");  
       try {
    // 1. Convertimos el texto ingresado a objetos Date
    Date fecha1 = sdf.parse(RecogerFecha1.getText());
    Date fecha2 = sdf.parse(RecogerFecha2.getText());

    // 2. Calculamos los milisegundos y la diferencia (tu código actual)
    long f1 = fecha1.getTime();
    long f2 = fecha2.getTime();
    long diferencia = Math.abs(f1 - f2);
    long dias = diferencia / (1000 * 60 * 60 * 24);

    // 3. Mostramos el resultado
    jTextFieldMensajeResultado.setText("La diferencia entre ambas fechas es " + dias);

} catch (Exception e) {
    jTextFieldMensajeResultado.setText("Por favor, introduce las fechas como dd/mm/aaaa");
}
    }//GEN-LAST:event_BtnCalcularActionPerformed

