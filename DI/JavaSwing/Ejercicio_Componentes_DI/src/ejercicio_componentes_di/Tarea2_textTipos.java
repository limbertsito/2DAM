    public void actualizarFuente() {
        int estilo = java.awt.Font.PLAIN;
        if (chkBoxNegrita.isSelected()) {
            estilo += java.awt.Font.BOLD;
        }
        if (chkBoxCursiva.isSelected()) {
            estilo += java.awt.Font.ITALIC;
        }
        jTextArea1.setFont(jTextArea1.getFont().deriveFont(estilo));
    }

