    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        String txtNif= fTxtRecogido.getText();
        
        if(txtNif.trim().length()<9|| txtNif.contains(" ")){
        jLabel1.setText("esta incompleto el texto actual tiene : "+txtNif.trim().length());
        
        }else{
        jLabel1.setText("Esta completo"+txtNif);
        // 3. Extraer los 8 números y la letra introducida
        int numero = Integer.parseInt(txtNif.substring(0, 8));
        char letraUsuario = txtNif.charAt(8);
        
        // 4. Calcular la letra correcta según el resto de dividir entre 23
        String letrasValidas = "TRWAGMYFPDXBNJZSQVHLCKE";
        int resto = numero % 23;
        char letraCorrecta = letrasValidas.charAt(resto);
        
        // 5. Mostrar el resultado en la etiqueta
        if (letraUsuario == letraCorrecta) {
            jLabel2.setText("NIF válido: " + txtNif);
        } else {
            jLabel2.setText("NIF " + txtNif + " incorrecto (letra esperada: " + letraCorrecta + ")");
        }
        
        }
        
    }//GEN-LAST:event_jButton1ActionPerformed

