    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        String plato1="Has elegido : \n";
        
        //Si se ha selccionado lo añadimos la texto
        if(jRadioButtonEnsalda.isSelected()){
        plato1+=" ensalada";
        }else if(jRadioButtonCroquetas.isSelected()){
            plato1+=" croquetas";
        }else if (jRadioButtonSopa.isSelected()){
            plato1+=" sopa castellana";
        }else{
            JOptionPane.showMessageDialog(this,"No has selccionado primer plato"," Faltan datos", JOptionPane.WARNING_MESSAGE);
        }
        
         //Si se ha selccionado lo añadimos la texto
        // tendremos que llamar a Component
        for (Component c :jPanel2.getComponents()) {
            JRadioButton rdb = (JRadioButton) c;
            if(rdb.isSelected()){
            plato1+=rdb.getText()+"\n";
            }
        }
        
        for(Component c : jPanel3.getComponents()){
            JCheckBox rdb = (JCheckBox) c;
            
            if(rdb.isSelected()){
            plato1+=rdb.getText()+" ";
            }
        }
        
        lblSalida.setText(plato1);
    }//GEN-LAST:event_jButton1ActionPerformed

